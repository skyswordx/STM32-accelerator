/**
 * @brief 简单的延时函数实现
 * @param us 延时时间（微秒）
 * @note 如果您需要更精确的延时，请使用AD9954_delay_test.c中的实现
 */
void delay_us(uint32_t us)
{
    // 简单的循环延时，需要根据系统时钟调整
    for(uint32_t i = 0; i < us * (SystemCoreClock / 1000000 / 10); i++) {
        __asm volatile ("nop");
    }
}
